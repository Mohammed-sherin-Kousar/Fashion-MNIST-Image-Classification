import tensorflow as tf
import keras
from tensorflow.keras import datasets,layers,models

import matplotlib.pyplot as plt
import numpy as np

import random

tf.random.set_seed(42)
np.random.seed(42)
random.seed(42)

# Load dataset

(x_train,y_train),(x_test,y_test) = keras.datasets.fashion_mnist.load_data()

x_train.shape

x_test.shape

y_train.shape

y_test.shape

classes = ['T-shirt/top', 'Trouser', 'Pullover', 'Dress', 'Coat',
               'Sandal', 'Shirt', 'Sneaker', 'Bag', 'Ankle boot']

print(y_train[0])

plt.imshow(x_train[0])

x_train[600]

# Normalization

x_train = x_train/255.0
x_test = x_test/255.0

# Reshape

x_train = x_train.reshape(-1,28,28,1)
x_test = x_test.reshape(-1,28,28,1)

x_train

classes = ['T-shirt/top', 'Trouser', 'Pullover', 'Dress', 'Coat',
               'Sandal', 'Shirt', 'Sneaker', 'Bag', 'Ankle boot']

x_train[0]

# Train/validation/test split

from sklearn.model_selection import train_test_split

x_train,x_val,y_train,y_val = train_test_split(x_train,y_train,test_size=0.2)

x_train.shape

x_test.shape

y_train.shape

y_test.shape

# Data Augumentation

from tensorflow.keras.preprocessing.image import ImageDataGenerator

datagen = ImageDataGenerator(
    rotation_range=10,
    zoom_range=0.1,
    width_shift_range=0.1,
    height_shift_range=0.1
)

"""**IMPLEMENTATION OF CNN**"""

cnn_dropout = models.Sequential()

# first Convolution layer

cnn_dropout.add(
    layers.Conv2D(filters=32,kernel_size=(3,3),activation='relu',input_shape=(28,28,1))
    )

# first MaxPool layer

cnn_dropout.add(
    layers.MaxPool2D((2,2))
)

# second Convolution layer

cnn_dropout.add(
    layers.Conv2D(filters=64,kernel_size=(3,3),activation='relu')
    )

# second MaxPool layer

cnn_dropout.add(
    layers.MaxPool2D((2,2))
)

# Flatten layer

cnn_dropout.add(
    layers.Flatten()
)

# Dense Layer with L2 Regularization

cnn_dropout.add(

    layers.Dense(128,activation='relu',kernel_regularizer=tf.keras.regularizers.l2(0.001))

)

# Fully connected layer

cnn_dropout.add(
    layers.Dense(64,activation='relu')

)

# Dropout Regularization

cnn_dropout.add(
    layers.Dropout(0.5)
)

# Output Layer

cnn_dropout.add(
    layers.Dense(10,activation='softmax')
)

# model summary

cnn_dropout.summary()

cnn_dropout.compile(
    optimizer='adam',loss='sparse_categorical_crossentropy',metrics=['accuracy']
    )

history_dropout = cnn_dropout.fit(datagen.flow(x_train, y_train, batch_size=32), validation_data=(x_val, y_val), epochs=10)

# cnn without dropout

cnn_no_dropout = models.Sequential([
    layers.Conv2D(32, (3,3), activation='relu', input_shape=(28,28,1)),
    layers.MaxPooling2D((2,2)),

    layers.Conv2D(64, (3,3), activation='relu'),
    layers.MaxPooling2D((2,2)),

    layers.Flatten(),

    layers.Dense(128,activation='relu',kernel_regularizer=tf.keras.regularizers.l2(0.001)),

    layers.Dense(64, activation='relu'),

    # Dropout removed

    layers.Dense(10, activation='softmax')
])

"""**COMPILE MODEL**"""

cnn_no_dropout.compile(
    optimizer='adam',loss='sparse_categorical_crossentropy',metrics=['accuracy']
    )

history_no_dropout = cnn_no_dropout.fit(datagen.flow(x_train, y_train, batch_size=32),validation_data=(x_val, y_val),epochs=10)

# comparision

print("With Dropout")
print("Validation Accuracy:", max(history_dropout.history['val_accuracy']))
print("Validation Loss:", min(history_dropout.history['val_loss']))

print()

print("Without Dropout")
print("Validation Accuracy:", max(history_no_dropout.history['val_accuracy']))
print("Validation Loss:", min(history_no_dropout.history['val_loss']))

"""EVALUATE MODEL"""

loss_dropout, acc_dropout = cnn_dropout.evaluate(x_test, y_test)

loss_no_dropout, acc_no_dropout = cnn_no_dropout.evaluate(x_test, y_test)

print("Test Accuracy with Dropout:", acc_dropout)
print("Test Accuracy without Dropout:", acc_no_dropout)

"""PREDICTIONS"""

predictions = cnn_dropout.predict(x_test)

predicted_classes = np.argmax(predictions, axis=1)

print(predictions)

# accuracy score

from sklearn.metrics import accuracy_score

